"""Invariants of the dose-response experiment, not of its analysis helpers.

Two of these are tests of a *claim* rather than of a function. The mixture axis
was re-run against a new degradation pool because the old one -- canon-8
decimated real builds -- was disavowed as a quality reference, and two things
had to be true for that re-run to mean anything:

* the corruption axes must be untouched by the swap, so that "solidify and
  occ_noise are unaffected" is checked rather than asserted; and
* the analysis must reproduce the published coefficients when fed the published
  run, so that a changed number is a changed *measurement* and not a changed
  formula.

Both are cheap to check and expensive to discover later.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from blockgen.utils.data import Structure
from scripts import bench_doseresponse as bdr

#: The run the paper's Table "response to the failure rate" was measured on.
#: Not tracked by git (outputs/ is ignored), so the test skips without it rather
#: than failing in a fresh clone.
PUBLISHED = Path("outputs/run_20260831_224723_doseresponse/doseresponse.json")


def _house(seed: int = 0, n: int = 9) -> Structure:
    rng = np.random.default_rng(seed)
    ids = np.zeros((n, n, n), dtype=np.int32)
    ids[:, 0, :] = 4
    ids[0, :, :] = ids[-1, :, :] = 5
    ids[:, :, 0] = ids[:, :, -1] = 5
    ids[:, -1, :] = 17
    # Random interior clutter, so two builds are never the same array: the
    # mixture tests count membership and would pass vacuously on clones.
    ids[1:-1, 1:-1, 1:-1] = np.where(
        rng.random((n - 2, n - 2, n - 2)) < 0.2, 35, 0)
    return Structure(block_ids=ids, block_data=np.zeros_like(ids))


def _pool(k: int = 6):
    return [_house(i) for i in range(k)]


def _ids(structs):
    return [s.block_ids.copy() for s in structs]


# --- the swap is confined to the mixture axis -------------------------------
def test_corruption_axes_do_not_depend_on_the_bad_pool():
    """`solidify`, `occ_noise` and `canon` must be bit-identical across pools.

    They share the run's `rng` with the mixture draws, so this is a real risk and
    not a formality: if the mixture consumed draws before them, swapping the bad
    pool would silently move three axes that have nothing to do with it.
    """
    pool = _pool()
    bad_a = {"alpha": [_house(100 + i) for i in range(len(pool))]}
    bad_b = {"beta": [_house(200 + i) for i in range(len(pool))],
             "gamma": [_house(300 + i) for i in range(len(pool))]}
    a = bdr.ladders(pool, np.random.default_rng(0), bad_a)
    b = bdr.ladders(pool, np.random.default_rng(0), bad_b)
    for axis in ("solidify", "occ_noise", "canon"):
        for (da, sa), (db, sb) in zip(a[axis], b[axis]):
            assert da == db
            for x, y in zip(_ids(sa), _ids(sb)):
                assert np.array_equal(x, y), axis


def test_each_mixture_rung_holds_the_arm_size_and_the_stated_dose():
    """The dose is the fraction of the arm that is NOT real, exactly."""
    pool = _pool(8)
    bad = {"junk": [_house(500 + i) for i in range(len(pool))]}
    axes = bdr.ladders(pool, np.random.default_rng(0), bad)
    real = {id(s) for s in pool}
    for dose, structs in axes["mixture_junk"]:
        assert len(structs) == len(pool)
        n_bad = sum(id(s) not in real for s in structs)
        assert n_bad == round(dose * len(pool))


def test_mix_seed_moves_the_mixture_and_nothing_else():
    pool = _pool(8)
    bad = {"junk": [_house(500 + i) for i in range(len(pool))]}
    base = bdr.ladders(pool, np.random.default_rng(0), bad)
    alt = bdr.ladders(pool, np.random.default_rng(0), bad,
                      np.random.default_rng(1234))
    for axis in ("solidify", "occ_noise", "canon"):
        for (_, sa), (_, sb) in zip(base[axis], alt[axis]):
            for x, y in zip(_ids(sa), _ids(sb)):
                assert np.array_equal(x, y), axis
    # Identity, not content: `mix` hands back the very objects it drew, so
    # "a different draw" means a different sequence of builds.
    differ = any([id(x) for x in sa] != [id(y) for y in sb]
                 for (_, sa), (_, sb) in zip(base["mixture_junk"],
                                             alt["mixture_junk"]))
    assert differ


# --- the analysis ------------------------------------------------------------
def test_mixture_fit_is_exact_on_a_synthetic_quadratic():
    """A curve generated by the identity must fit it with zero error, and the
    square root must invert it exactly. Anything else is an arithmetic bug."""
    dose = np.array([0.0, 0.25, 0.5, 0.75, 1.0])
    value = 0.0 + 0.5 * dose ** 2
    f = bdr.mixture_fit(dose, value)
    assert f["abs_err_quadratic"] == pytest.approx(0.0, abs=1e-12)
    assert f["abs_err_linear"] > 0.1
    assert f["exponent_best_fit"] == pytest.approx(2.0, abs=0.02)
    assert f["mae_sqrt"] == pytest.approx(0.0, abs=1e-9)
    assert f["mae_raw"] > 0.1


def test_mixture_fit_needs_both_endpoints():
    with pytest.raises(ValueError):
        bdr.mixture_fit([0.0, 0.25, 0.5], [0.0, 0.1, 0.4])


def test_negative_kid_is_clamped_not_propagated_as_nan():
    """An unbiased KID estimator is legitimately negative on real-vs-real, which
    is the dose-0 rung of every mixture axis. `sqrt` of it must not be a NaN."""
    f = bdr.mixture_fit([0.0, 0.5, 1.0], [-0.002, 0.15, 0.55])
    assert np.isfinite(f["recovered_sqrt"]).all()
    assert f["recovered_sqrt"][0] == 0.0


@pytest.mark.skipif(not PUBLISHED.exists(), reason="published run not on disk")
def test_mixture_fit_reproduces_the_published_coefficients():
    """The paper's §5 numbers, recomputed from the run they were measured on.

    Pins the formula so that the new bad pool's coefficients differ because the
    *pool* changed. Tolerances are the paper's own rounding.
    """
    axes = json.loads(PUBLISHED.read_text())["axes"]["mixture"]
    dino = bdr.mixture_fit(axes["mv_dino_kid"]["dose"], axes["mv_dino_kid"]["value"])
    geo = bdr.mixture_fit(axes["geom_kid"]["dose"], axes["geom_kid"]["value"])
    assert dino["abs_err_quadratic"] == pytest.approx(0.023, abs=0.001)
    assert dino["abs_err_linear"] == pytest.approx(0.325, abs=0.001)
    assert dino["quadratic_better_by"] == pytest.approx(14.0, abs=0.5)
    assert dino["mae_sqrt"] == pytest.approx(0.022, abs=0.001)
    assert dino["mae_raw"] == pytest.approx(0.119, abs=0.001)
    assert geo["mae_sqrt"] == pytest.approx(0.028, abs=0.001)
    assert geo["mae_raw"] == pytest.approx(0.142, abs=0.001)
