"""Legacy (pre-1.13) block-id classes used to tell player-built from generated.

Three tiers, over numeric ids (data values ignored unless listed):

* ``STRONG`` - essentially never produced by vanilla terrain generation outside the
  structures we mask (villages, strongholds, mineshafts, temples, monuments,
  fortresses). These *seed* a candidate structure.
* ``WEAK``   - common in player builds but also natural (cobblestone, logs, hardened
  clay, obsidian, chests, mossy cobble...). They may *grow* a component but never
  start one, so a dungeon (cobble + chest + spawner) yields no candidate.
* everything else (terrain, fluids, plants, ores, leaves, bedrock) never belongs to a
  component; it is kept only as context inside a crop's bounding box.

Flat worlds get a different rule (see :func:`flat_layers`): every block that is not
part of the declared layer stack is player-placed, except a short list of
decoration/fluid blocks the flat generator may still spawn.
"""
from __future__ import annotations

import re
from typing import Dict, List, Optional, Tuple

import numpy as np

