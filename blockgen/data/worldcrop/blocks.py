_LEGACY_NAME_TO_ID: Optional[Dict[str, int]] = None


def legacy_name_to_id() -> Dict[str, int]:
    """'minecraft:planks' -> 5, from the project's STANDARD_VOCAB."""
    global _LEGACY_NAME_TO_ID
    if _LEGACY_NAME_TO_ID is None:
        from blockgen.tokenizers.standard_vocab import STANDARD_VOCAB
        m: Dict[str, int] = {}
        for key, label in STANDARD_VOCAB.items():
            bid = int(str(key).split(":")[0])
            r = re.search(r"\(([^)]+)\)", label)
            if r:
                name = r.group(1)
                m.setdefault(name, bid)
                m.setdefault(name.split(":", 1)[-1], bid)
        _LEGACY_NAME_TO_ID = m
    return _LEGACY_NAME_TO_ID


DEFAULT_FLAT_LAYERS = [(7, 1), (3, 2), (2, 1)]  # bedrock, 2 dirt, grass


def flat_layers(generator_options: str) -> List[Tuple[int, int]]:
    """Parse a 1.x superflat preset into [(block_id, count), ...] bottom-up.

    Formats: ``"3;minecraft:bedrock,2*minecraft:dirt,minecraft:grass;1;village"`` (1.8+),
    ``"2;7,2x3,2;1;village"`` (1.3-1.7), ``"7,2x3,2;1"`` (1.2). Empty -> default preset.
    An all-air preset (``"3;minecraft:air;..."``) is the void world."""
    s = (generator_options or "").strip()
    if not s:
        return list(DEFAULT_FLAT_LAYERS)
    parts = s.split(";")
    layers_str = parts[1] if len(parts) > 1 and parts[0].strip().isdigit() else parts[0]
    names = legacy_name_to_id()
    out: List[Tuple[int, int]] = []
    for item in layers_str.split(","):
        item = item.strip()
        if not item:
            continue
        count = 1
        m = re.match(r"^(\d+)\s*[x*]\s*(.+)$", item)
        if m:
            count, item = int(m.group(1)), m.group(2)
        item = item.split(":")[0] if item.split(":")[0].isdigit() else item
        if item.isdigit():
            bid = int(item)
        else:
            base = item
            # strip a trailing numeric data value "minecraft:stone:1"
            mm = re.match(r"^(minecraft:[a-z_]+):\d+$", base)
            if mm:
                base = mm.group(1)
            bid = names.get(base, names.get(base.replace("minecraft:", ""), -1))
            if bid < 0:
                bid = 1  # unknown -> stone-ish; still treated as terrain
        out.append((bid, max(count, 0)))
    return out or list(DEFAULT_FLAT_LAYERS)


def flat_column(layers: List[Tuple[int, int]], height: int = 256) -> np.ndarray:
    """Expected block id at each y for a flat preset."""
    col = np.zeros(height, np.uint16)
    y = 0
    for bid, cnt in layers:
        col[y : y + cnt] = bid
        y += cnt
    return col
