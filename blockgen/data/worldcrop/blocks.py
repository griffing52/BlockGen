def class_tables() -> Tuple[np.ndarray, np.ndarray]:
    """Return (strong_lut, weak_lut) boolean arrays indexed by block id."""
    strong = np.zeros(MAX_ID, bool)
    weak = np.zeros(MAX_ID, bool)
    strong[list(STRONG)] = True
    weak[list(WEAK)] = True
    weak &= ~strong
    return strong, weak


def classify(ids: np.ndarray, data: np.ndarray, strong_lut: np.ndarray, weak_lut: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """Per-voxel (is_strong, is_weak) masks; handles the (id,data) promotions."""
    s = strong_lut[ids]
    w = weak_lut[ids]
    for bid, bdat in STRONG_ID_DATA:
        promote = (ids == bid) & (data == bdat)
        s |= promote
        w &= ~promote
    return s, w


